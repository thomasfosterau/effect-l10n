/**
 * The web target: one tree-shakeable ES module per message, typed by its
 * `.d.ts`, over a small generated runtime that resolves the locale through
 * the configured strategies. The output is plain JavaScript that calls
 * `Intl` directly: no Effect and no MessageFormat parser.
 *
 * @since 0.1.0
 */
import type * as Config from "@thomasfosterau/effect-l10n/Config";
import type * as Lowering from "@thomasfosterau/effect-l10n/compiler/Lowering";
import { directionOf } from "@thomasfosterau/effect-l10n/messageformat/Formatter";
import { type FileTree, make, type Target } from "@thomasfosterau/effect-l10n/compiler/Target";
import * as Arr from "effect/Array";
import * as Effect from "effect/Effect";
import * as Option from "effect/Option";
import * as R from "effect/Record";
import * as Schema from "effect/Schema";
import * as Str from "effect/String";
import { helpersUsed, implementation, quote } from "./internal/codegen";
import { formatDeclarations, formatModule, functions } from "./internal/format";
import {
  runtimeDeclarations,
  runtimeModule,
  serverDeclarations,
  serverModule,
  Strategy,
} from "./internal/runtime";
import { docComment, messageType } from "./internal/types";

export { Strategy } from "./internal/runtime";

const withDefault = <S extends Schema.Top>(schema: S, value: S["Encoded"]) =>
  schema.pipe(Schema.withDecodingDefaultKey(Effect.succeed(value)));

/**
 * The cookie the `cookie` strategy reads and `setLocale` writes.
 *
 * @category options
 * @since 0.1.0
 */
export const CookieOptions = Schema.Struct({
  name: withDefault(Schema.String, "l10n-locale"),
  /** In seconds; 400 days, the most browsers keep, by default. */
  maxAge: withDefault(Schema.Int, 34_560_000),
  domain: Schema.optionalKey(Schema.String),
});

/**
 * @category options
 * @since 0.1.0
 */
export type CookieOptions = typeof CookieOptions.Type;

/**
 * How the `url` strategy puts the locale in a URL.
 *
 * - `mode`: a path `prefix` (`/de/about`), or a `domain` per locale.
 * - `prefixBaseLocale`: whether the base locale has a prefix too.
 * - `domains`: each locale's host, for `domain` mode.
 * - `pathnames`: localised paths, by canonical path and then locale, such
 *   as `{ "/about": { de: "/ueber-uns" } }`.
 *
 * @category options
 * @since 0.1.0
 */
export const UrlOptions = Schema.Struct({
  mode: withDefault(Schema.Literals(["prefix", "domain"]), "prefix"),
  prefixBaseLocale: withDefault(Schema.Boolean, false),
  domains: Schema.optionalKey(Schema.Record(Schema.String, Schema.String)),
  pathnames: withDefault(
    Schema.Record(Schema.String, Schema.Record(Schema.String, Schema.String)),
    {},
  ),
});

/**
 * @category options
 * @since 0.1.0
 */
export type UrlOptions = typeof UrlOptions.Type;

/**
 * The web target's options.
 *
 * - `strategy`: where the runtime looks for the locale, in order.
 * - `cookie`, `localStorageKey`, `url`: each strategy's settings.
 * - `output`: `js` for `.js` with `.d.ts`, or `ts` for TypeScript message
 *   modules.
 *
 * @category options
 * @since 0.1.0
 */
export const Options = Schema.Struct({
  strategy: withDefault(Schema.Array(Strategy), [
    "cookie",
    "globalVariable",
    "preferredLanguage",
    "baseLocale",
  ]),
  cookie: withDefault(CookieOptions, {}),
  localStorageKey: withDefault(Schema.String, "l10n-locale"),
  url: withDefault(UrlOptions, {}),
  output: withDefault(Schema.Literals(["js", "ts"]), "js"),
}).check(
  Schema.makeFilter(
    (options) =>
      !Arr.contains(options.strategy, "url") ||
      options.url.mode !== "domain" ||
      options.url.domains !== undefined ||
      "the url strategy's domain mode needs url.domains",
    {
      identifier: "DomainsForDomainMode",
      title: "domains for domain mode",
      description: "url.domains is set when the url strategy uses domain mode",
    },
  ),
);

/**
 * @category options
 * @since 0.1.0
 */
export type Options = typeof Options.Type;

const reserved = Str.split(
  "arguments await break case catch class const continue debugger default delete do else enum eval export extends false finally for function if implements import in instanceof interface let new null package private protected public return static super switch this throw true try typeof var void while with yield",
  " ",
);

/**
 * A message ID's export name: its segments in `camelCase`, joined by `_`
 * (`checkout_totalPrice` for `checkout.totalPrice`).
 *
 * @category identifiers
 * @since 0.1.0
 */
export const identifierOf = (id: string): string => {
  const name = Arr.join(Arr.map(Str.split(id, "."), Str.camelCase), "_");
  return Arr.contains(reserved, name) ? `${name}_` : name;
};

const header = "// Generated by effect-l10n. Do not edit.\n";

/** A message's module: its locales' implementations, shared where they are the same. */
const messageModule = (message: Lowering.Message, output: Options["output"]): string => {
  const name = identifierOf(message.id);
  const byLocale = R.map(message.locales, implementation);
  const distinct = Arr.dedupe(R.values(byLocale));
  const constant = (code: string) =>
    `_${Option.getOrElse(
      Arr.findFirstIndex(distinct, (d) => d === code),
      () => 0,
    )}`;
  const typed = output === "ts" ? ": Impl" : "";
  const body = `${Arr.join(
    Arr.map(distinct, (code, i) => `const _${i}${typed} = ${code};`),
    "\n\n",
  )}

${docComment(message)}export const ${name}${
    output === "ts" ? `: ${messageType(message, message.params)}` : ""
  } = /* @__PURE__ */ $message({ ${Arr.join(
    Arr.map(R.toEntries(byLocale), ([locale, code]) => `${quote(locale)}: ${constant(code)}`),
    ", ",
  )} });
`;
  const imports = `import { ${Arr.join(helpersUsed(body), ", ")} } from "../internal.js";\n`;
  const types =
    output === "ts"
      ? `import type { Impl } from "../internal.js";\nimport type { Message } from "../runtime.js";\n`
      : "";
  return `${header}${imports}${types}\n${body}`;
};

const messageDeclarations = (message: Lowering.Message): string =>
  `${header}import type { Message } from "../runtime.js";

${docComment(message)}export declare const ${identifierOf(message.id)}: ${messageType(
    message,
    message.params,
  )};
`;

/** Every emitted file of a lowered project. */
const files = (project: Lowering.Project, options: Options): FileTree => {
  const locales = Arr.map(project.locales, String);
  const base = String(project.sourceLocale);
  const extension = options.output === "ts" ? "ts" : "js";
  const directions = `{ ${Arr.join(
    Arr.map(locales, (l) => `${quote(l)}: ${quote(directionOf(l))}`),
    ", ",
  )} }`;
  const perMessage = Arr.flatMap(project.messages, (message): Array<readonly [string, string]> => [
    [`messages/${message.id}.${extension}`, messageModule(message, options.output)],
    ...(options.output === "js"
      ? [[`messages/${message.id}.d.ts`, messageDeclarations(message)] as const]
      : []),
  ]);
  const barrel = `${header}${Arr.join(
    Arr.map(
      project.messages,
      (m) => `export { ${identifierOf(m.id)} } from "./messages/${m.id}.js";\n`,
    ),
    "",
  )}`;
  return R.fromEntries([
    ["runtime.js", runtimeModule(locales, base, options)],
    ["runtime.d.ts", runtimeDeclarations(locales, base, options)],
    ["internal.js", formatModule(directions)],
    ["internal.d.ts", formatDeclarations],
    ["server.js", serverModule(options)],
    ["server.d.ts", serverDeclarations],
    [`messages.${extension}`, barrel],
    ...(options.output === "js" ? [["messages.d.ts", barrel] as const] : []),
    ...perMessage,
  ]);
};

/**
 * The web target itself.
 *
 * @category targets
 * @since 0.1.0
 */
export const target: Target<typeof Options> = {
  name: "web",
  options: Options,
  capabilities: {
    selectors: "any",
    hasExactKeys: true,
    functions,
    markup: "keep",
    // Nothing formats ahead of the generated code, so a function it doesn't
    // implement is reported rather than preformatted.
    hasAccessors: false,
  },
  // A function it doesn't implement falls back, as the reference does for
  // an unknown one: formatting it is reported as unsupported in lowering.
  emit: (project, options) => Effect.succeed(files(project, options)),
};

/**
 * Lists the web target in a config: `targets: [web({ strategy: ["url", "cookie", "baseLocale"] })]`.
 *
 * @category constructors
 * @since 0.1.0
 */
export const web: (options: typeof Options.Encoded) => Config.Target<typeof Options> = make(target);
